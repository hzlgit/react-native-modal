import { Easing } from 'react-native';

function fade(
  entering: boolean,
  axis: 'translateX' | 'translateY',
  distance: number,
) {
  const hidden = { opacity: 0, [axis]: distance };
  const visible = { opacity: 1, [axis]: 0 };
  return entering
    ? { from: hidden, to: visible }
    : { from: visible, to: hidden };
}

